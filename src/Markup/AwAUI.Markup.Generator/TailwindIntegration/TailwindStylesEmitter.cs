using System.Text;

namespace AwAUI.Markup.Generator.TailwindIntegration;

/// <summary>
/// 生成 <c>TailwindStyles</c> 类：
/// <code>
/// internal static partial class TailwindStyles
/// {
///     public const string SourceName = "tailwind:Styles/app.css";
///     public const string Css = @"...";                       // 构建期生成的整份样式表
///     public static IReadOnlyList&lt;string&gt; Candidates { get; } // 生成了样式的类名（运行时补全的基线）
///     [ModuleInitializer] public static void Register() => AppStyleSheets.Register(Css, SourceName);
/// }
/// </code>
/// 引用了 AwAUI.UI 才生成 <c>Register</c>；AwAUITailwindRegister=false 或 C# 9 以下时不加模块初始化器（由应用自己调用）。
/// </summary>
internal static class TailwindStylesEmitter
{
    public const string ModuleInitializerPolyfill =
        "// <auto-generated/>\n" +
        "// AwAUI.Markup：目标框架没有 ModuleInitializerAttribute（netstandard2.0 / .NET Framework），编译器按名称识别这个内部特性。\n" +
        "namespace System.Runtime.CompilerServices\n" +
        "{\n" +
        "    [global::System.AttributeUsage(global::System.AttributeTargets.Method, Inherited = false)]\n" +
        "    internal sealed class ModuleInitializerAttribute : global::System.Attribute\n" +
        "    {\n" +
        "    }\n" +
        "}\n";

    public static string Emit(EntryResult result, TailwindCompilationInfo info)
    {
        var entry = result.Entry;
        var settings = entry.Settings;
        // 来源名带程序集名：库（如 AwAUI.Shadcn）与应用的入口样式表可能同名，AppStyleSheets 按来源名去重
        string sourceName = "tailwind:" + (settings.AssemblyName.Length > 0 ? settings.AssemblyName + "/" : "") + entry.RelativePath;
        var sb = new StringBuilder((result.Css?.Length ?? 0) + result.Candidates.Count * 24 + 2048);
        sb.Append("// <auto-generated/>\n");
        sb.Append("// AwAUI.Markup：Tailwind 入口样式表 ").Append(entry.RelativePath).Append(" 的构建期输出（design/23）。\n");
        sb.Append("#nullable enable\n");
        sb.Append("namespace ").Append(settings.RootNamespace).Append("\n{\n");
        sb.Append("    /// <summary>Tailwind 样式表 <c>").Append(Xml(entry.RelativePath)).Append("</c> 按项目中用到的类名生成的 CSS（AwAUI.Markup 源生成器）。</summary>\n");
        sb.Append("    [global::System.CodeDom.Compiler.GeneratedCode(\"AwAUI.Markup\", \"1.0\")]\n");
        sb.Append("    internal static partial class ").Append(entry.ClassName).Append("\n    {\n");
        sb.Append("        /// <summary>来源名（诊断与 DevTools 显示，也是 <c>AppStyleSheets</c> 的登记键）。</summary>\n");
        sb.Append("        public const string SourceName = ").Append(CSharpLiterals.String(sourceName)).Append(";\n\n");
        sb.Append("        /// <summary>生成的样式表。</summary>\n");
        sb.Append("        public const string Css = ").Append(CSharpLiterals.Verbatim(result.Css ?? "")).Append(";\n\n");
        sb.Append("        /// <summary>生成了样式的类名（按序数排序）：运行时补全以它们为基线（先 <c>Build([])</c>，再 <c>AddCandidates(Candidates)</c>）。</summary>\n");
        sb.Append("        public static global::System.Collections.Generic.IReadOnlyList<string> Candidates { get; } = new string[]\n        {\n");
        foreach (var c in result.Candidates) sb.Append("            ").Append(CSharpLiterals.String(c)).Append(",\n");
        sb.Append("        };\n");
        if (info.HasAppStyleSheets)
        {
            bool init = settings.Register && info.LanguageSupportsModuleInitializer;
            sb.Append("\n        /// <summary>\n");
            sb.Append("        /// 把 <see cref=\"Css\"/> 登记到 <see cref=\"global::AwAUI.UI.AppStyleSheets\"/>（之后每个渲染管线在下一帧加入级联）。");
            sb.Append(init ? "模块初始化时已自动调用；重复调用无害。\n" : "未启用自动登记（AwAUITailwindRegister=false 或 C# 9 以下），由应用在创建界面前调用。\n");
            sb.Append("        /// </summary>\n");
            if (init) sb.Append("        [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
            sb.Append("        public static void Register() => global::AwAUI.UI.AppStyleSheets.Register(Css, SourceName);\n");
        }
        sb.Append("    }\n}\n");
        return sb.ToString();
    }

    static string Xml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
