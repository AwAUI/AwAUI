using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace AwAUI.Tools.UnicodeDataGen;

/// <summary>
/// 从 Unicode 字符数据库（UCD）生成 AwAUI.Unicode 的查找表与属性枚举。输出确定：相同输入得到逐字节相同的文件。
/// 用法：dotnet run --project src/tools/UnicodeDataGen -c Release -- [--cache 目录] [--out 目录] [--version 18.0.0] [--offline]
/// </summary>
internal static class Program
{
    const string DefaultVersion = "18.0.0";

    static int Main(string[] args)
    {
        string version = DefaultVersion;
        string? cache = null, output = null;
        bool offline = false;
        for (int i = 0; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--cache": cache = args[++i]; break;
                case "--out": output = args[++i]; break;
                case "--version": version = args[++i]; break;
                case "--offline": offline = true; break;
                default:
                    Console.Error.WriteLine($"unknown argument: {args[i]}");
                    Console.Error.WriteLine("usage: UnicodeDataGen [--cache <dir>] [--out <dir>] [--version <x.y.z>] [--offline]");
                    return 2;
            }
        }
        var root = FindRepoRoot();
        cache ??= Path.Combine(Path.GetTempPath(), "awaui-ucd-" + version);
        output ??= Path.Combine(root, "src", "AwAUI.Unicode", "Generated");
        var ucd = new Ucd(cache, $"https://www.unicode.org/Public/{version}/ucd/", !offline);
        var gen = new Generator(ucd, version);
        gen.Run(output);
        return 0;
    }

    static string FindRepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "global.json"))) dir = dir.Parent;
        if (dir != null) return dir.FullName;
        dir = new DirectoryInfo(Directory.GetCurrentDirectory());
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "global.json"))) dir = dir.Parent;
        return dir?.FullName ?? throw new InvalidOperationException("Repository root (global.json) not found.");
    }
}

internal sealed class Generator
{
    const int N = Ucd.CodePointCount;
    readonly Ucd _ucd;
    readonly string _version;
    readonly List<(string File, string Content)> _files = new();
    readonly List<(string Name, int Bytes)> _sizes = new();

    public Generator(Ucd ucd, string version)
    {
        _ucd = ucd;
        _version = version;
    }

    string Header() =>
        "// <auto-generated>\n" +
        $"// 由 src/tools/UnicodeDataGen 从 Unicode 字符数据库（UCD）{_version} 生成，请勿手工修改。\n" +
        "// 生成命令：dotnet run --project src/tools/UnicodeDataGen -c Release -- [--cache <UCD 缓存目录>]\n" +
        $"// 数据来源：https://www.unicode.org/Public/{_version}/ucd/ ，Unicode 许可见同目录 UNICODE-LICENSE.txt。\n" +
        "// </auto-generated>\n";

    public void Run(string outDir)
    {
        _ucd.LoadAliases();
        var fileVersion = _ucd.ReadVersionTag("LineBreak.txt");
        if (fileVersion != _version) throw new InvalidDataException($"UCD files are version {fileVersion}, expected {_version}.");

        // ---------- 枚举 ----------
        var gcSpec = EnumSpec.GeneralCategory();
        var lbSpec = EnumSpec.LineBreak();
        var gcbSpec = EnumSpec.GraphemeClusterBreak();
        var wbSpec = EnumSpec.WordBreak();
        var sbSpec = EnumSpec.SentenceBreak();
        var incbSpec = EnumSpec.IndicConjunctBreak();
        var eaSpec = EnumSpec.EastAsianWidth();
        var bcSpec = EnumSpec.BidiClass();
        var bptSpec = EnumSpec.BidiPairedBracketType();
        var jtSpec = EnumSpec.JoiningType();
        var voSpec = EnumSpec.VerticalOrientation();
        var scSpec = EnumSpec.FromAliases(_ucd, "Script", "Unicode 文字（Script）。数值随 Unicode 版本可能变化，持久化请用 ISO 15924 代码。", "sc",
            new[] { "Zzzz", "Zyyy", "Zinh" }, "{1}（{0}）。");
        var jgSpec = EnumSpec.FromAliases(_ucd, "JoiningGroup", "Joining_Group（ArabicShaping.txt），阿拉伯/叙利亚等文字的字母连写分组。", "jg",
            new[] { "No_Joining_Group" }, "{1}。");
        var inscSpec = EnumSpec.FromAliases(_ucd, "IndicSyllabicCategory", "Indic_Syllabic_Category，印度系与东南亚文字整形使用。", "InSC",
            new[] { "Other" }, "{1}。");
        var inpcSpec = EnumSpec.FromAliases(_ucd, "IndicPositionalCategory", "Indic_Positional_Category，印度系组合符号的相对位置。", "InPC",
            new[] { "NA" }, "{1}。");

        // ---------- 读取属性 ----------
        var gc = Fill(gcSpec.IndexOfShort("Cn"));
        _ucd.ReadEnumerated("extracted/DerivedGeneralCategory.txt", "gc", null, gcSpec.IndexOfShort, gc);
        var sc = Fill(0);
        _ucd.ReadEnumerated("Scripts.txt", "sc", null, scSpec.IndexOfShort, sc);
        var lb = Fill(0);
        _ucd.ReadEnumerated("LineBreak.txt", "lb", null, lbSpec.IndexOfShort, lb);
        var gcb = Fill(0);
        _ucd.ReadEnumerated("auxiliary/GraphemeBreakProperty.txt", "GCB", null, gcbSpec.IndexOfShort, gcb);
        var wb = Fill(0);
        _ucd.ReadEnumerated("auxiliary/WordBreakProperty.txt", "WB", null, wbSpec.IndexOfShort, wb);
        var sb = Fill(0);
        _ucd.ReadEnumerated("auxiliary/SentenceBreakProperty.txt", "SB", null, sbSpec.IndexOfShort, sb);
        var incb = Fill(0);
        _ucd.ReadEnumerated("DerivedCoreProperties.txt", "InCB", "InCB", incbSpec.IndexOfShort, incb);
        var ea = Fill(0);
        _ucd.ReadEnumerated("EastAsianWidth.txt", "ea", null, eaSpec.IndexOfShort, ea);
        var bc = Fill(0);
        _ucd.ReadEnumerated("extracted/DerivedBidiClass.txt", "bc", null, bcSpec.IndexOfShort, bc);
        var jt = Fill(0);
        _ucd.ReadEnumerated("extracted/DerivedJoiningType.txt", "jt", null, jtSpec.IndexOfShort, jt);
        var jg = Fill(0);
        _ucd.ReadEnumerated("extracted/DerivedJoiningGroup.txt", "jg", null, jgSpec.IndexOfShort, jg);
        var insc = Fill(0);
        _ucd.ReadEnumerated("IndicSyllabicCategory.txt", "InSC", null, inscSpec.IndexOfShort, insc);
        var inpc = Fill(0);
        _ucd.ReadEnumerated("IndicPositionalCategory.txt", "InPC", null, inpcSpec.IndexOfShort, inpc);
        var vo = Fill(0);
        _ucd.ReadEnumerated("VerticalOrientation.txt", "vo", null, voSpec.IndexOfShort, vo);

        var extPict = _ucd.ReadBinary("emoji/emoji-data.txt", "Extended_Pictographic");
        var emoji = _ucd.ReadBinary("emoji/emoji-data.txt", "Emoji");
        var emojiPres = _ucd.ReadBinary("emoji/emoji-data.txt", "Emoji_Presentation");
        var emojiMod = _ucd.ReadBinary("emoji/emoji-data.txt", "Emoji_Modifier");
        var emojiModBase = _ucd.ReadBinary("emoji/emoji-data.txt", "Emoji_Modifier_Base");
        var emojiComp = _ucd.ReadBinary("emoji/emoji-data.txt", "Emoji_Component");
        var defaultIgnorable = _ucd.ReadBinary("DerivedCoreProperties.txt", "Default_Ignorable_Code_Point");
        var whiteSpace = _ucd.ReadBinary("PropList.txt", "White_Space");

        foreach (var (spec, data) in new[] { (gcSpec, gc), (lbSpec, lb), (gcbSpec, gcb), (wbSpec, wb), (sbSpec, sb), (incbSpec, incb), (eaSpec, ea), (bcSpec, bc), (jtSpec, jt), (voSpec, vo) })
            spec.CheckAllUsed(data);

        // UnicodeData.txt：Bidi_Mirrored 与简单大小写映射
        var mirrored = new bool[N];
        var lower = new int[N];
        var upper = new int[N];
        var title = new int[N];
        var ccc = new int[N];
        foreach (var raw in _ucd.ReadLines("UnicodeData.txt"))
        {
            if (raw.Length == 0) continue;
            var f = raw.Split(';');
            int cp = Ucd.ParseHex(f[0]);
            // Canonical_Combining_Class（范围条目 First / Last 的组合类都是 0，不必展开）
            ccc[cp] = int.Parse(f[3], CultureInfo.InvariantCulture);
            if (f[9] == "Y") mirrored[cp] = true;
            if (f[12].Length > 0) upper[cp] = Ucd.ParseHex(f[12]) - cp;
            if (f[13].Length > 0) lower[cp] = Ucd.ParseHex(f[13]) - cp;
            // Simple_Titlecase_Mapping 为空时等于 Simple_Uppercase_Mapping（UAX #44）
            title[cp] = f[14].Length > 0 ? Ucd.ParseHex(f[14]) - cp : upper[cp];
        }

        // Script_Extensions：码位 → 文字集合编号（0 = 未显式给出，等于 Script）
        var scxSets = new List<byte[]> { Array.Empty<byte>() };
        var scxIndex = new Dictionary<string, int>();
        var scx = Fill(0);
        foreach (var raw in _ucd.ReadLines("ScriptExtensions.txt"))
        {
            var line = Ucd.StripComment(raw);
            if (line.Length == 0) continue;
            var f = Ucd.Split(line);
            var (lo, hi) = Ucd.ParseRange(f[0]);
            var set = f[1].Split(' ', StringSplitOptions.RemoveEmptyEntries)
                .Select(s => (byte)scSpec.IndexOfShort(_ucd.ToShortName("sc", s))).OrderBy(b => b).ToArray();
            var key = string.Join(",", set);
            if (!scxIndex.TryGetValue(key, out var idx))
            {
                idx = scxSets.Count;
                scxSets.Add(set);
                scxIndex[key] = idx;
            }
            for (int cp = lo; cp <= hi; cp++) scx[cp] = idx;
        }

        // 括号与镜像
        var bpt = Fill(0);
        var brackets = new SortedDictionary<int, int>();
        foreach (var raw in _ucd.ReadLines("BidiBrackets.txt"))
        {
            var line = Ucd.StripComment(raw);
            if (line.Length == 0) continue;
            var f = Ucd.Split(line);
            int cp = Ucd.ParseHex(f[0]);
            brackets[cp] = Ucd.ParseHex(f[1]);
            bpt[cp] = bptSpec.IndexOfShort(_ucd.ToShortName("bpt", f[2]));
        }
        var mirrors = new SortedDictionary<int, int>();
        foreach (var raw in _ucd.ReadLines("BidiMirroring.txt"))
        {
            var line = Ucd.StripComment(raw);
            if (line.Length == 0) continue;
            var f = Ucd.Split(line);
            mirrors[Ucd.ParseHex(f[0])] = Ucd.ParseHex(f[1]);
        }

        // ---------- 打包 ----------
        int gcPi = gcSpec.IndexOfShort("Pi"), gcPf = gcSpec.IndexOfShort("Pf"), gcCn = gcSpec.IndexOfShort("Cn");
        int gcMn = gcSpec.IndexOfShort("Mn"), gcMc = gcSpec.IndexOfShort("Mc");
        var segment = new int[N];
        var line_ = new int[N];
        var bidi = new int[N];
        var flags = new int[N];
        var shaping = new int[N];
        for (int cp = 0; cp < N; cp++)
        {
            segment[cp] = gcb[cp] | (incb[cp] << 4) | (B(extPict[cp]) << 6) | (wb[cp] << 7) | (sb[cp] << 12);
            line_[cp] = lb[cp] | (ea[cp] << 6) | (B(gc[cp] == gcPi) << 9) | (B(gc[cp] == gcPf) << 10)
                        | (B(extPict[cp]) << 11) | (B(gc[cp] == gcCn) << 12) | (B(gc[cp] == gcMn || gc[cp] == gcMc) << 13);
            bidi[cp] = bc[cp] | (bpt[cp] << 5) | (B(mirrored[cp]) << 7);
            flags[cp] = B(emoji[cp]) | (B(emojiPres[cp]) << 1) | (B(emojiMod[cp]) << 2) | (B(emojiModBase[cp]) << 3)
                        | (B(emojiComp[cp]) << 4) | (B(defaultIgnorable[cp]) << 5) | (B(whiteSpace[cp]) << 6);
            shaping[cp] = jt[cp] | (insc[cp] << 3) | (inpc[cp] << 9) | (vo[cp] << 13);
        }
        if (gcbSpec.Members.Count > 16 || incbSpec.Members.Count > 4 || wbSpec.Members.Count > 32 || sbSpec.Members.Count > 16
            || lbSpec.Members.Count > 64 || eaSpec.Members.Count > 8 || bcSpec.Members.Count > 32 || jtSpec.Members.Count > 8
            || inscSpec.Members.Count > 64 || inpcSpec.Members.Count > 16 || voSpec.Members.Count > 4 || scSpec.Members.Count > 256
            || jgSpec.Members.Count > 256)
            throw new InvalidDataException("A property no longer fits its packed bit field; update the layout.");

        // 大小写：三元组 (lower, upper, title) 差值去重
        var caseRecords = new List<(int L, int U, int T)> { (0, 0, 0) };
        var caseIndex = new Dictionary<(int, int, int), int> { [(0, 0, 0)] = 0 };
        var caseTrie = new int[N];
        for (int cp = 0; cp < N; cp++)
        {
            var rec = (lower[cp], upper[cp], title[cp]);
            if (!caseIndex.TryGetValue(rec, out var idx))
            {
                idx = caseRecords.Count;
                caseRecords.Add(rec);
                caseIndex[rec] = idx;
            }
            caseTrie[cp] = idx;
        }

        // ---------- 生成 ----------
        var enums = new StringBuilder();
        enums.Append(Header()).Append("\nnamespace AwAUI.Unicode;\n\n");
        foreach (var spec in new[] { gcSpec, scSpec, lbSpec, gcbSpec, wbSpec, sbSpec, incbSpec, eaSpec, bcSpec, bptSpec, jtSpec, jgSpec, inscSpec, inpcSpec, voSpec })
            spec.Emit(enums);
        _files.Add(("UnicodeEnums.g.cs", enums.ToString().TrimEnd('\n') + "\n"));

        EmitTrie("GeneralCategory", gc, 1, "General_Category。");
        EmitTrie("Script", sc, 1, "Script。");
        EmitTrie("ScriptExtensions", scx, scxSets.Count <= 256 ? 1 : 2, "Script_Extensions 集合编号（0 表示与 Script 相同）。");
        EmitTrie("Segment", segment, 2, "分段属性打包：GCB[0..3] InCB[4..5] ExtPict[6] WB[7..11] SB[12..15]。");
        EmitTrie("Line", line_, 2, "断行属性打包：LB[0..5] EAW[6..8] Pi[9] Pf[10] ExtPict[11] Cn[12] Mn/Mc[13]。");
        EmitTrie("Bidi", bidi, 1, "双向属性打包：Bidi_Class[0..4] Bidi_Paired_Bracket_Type[5..6] Bidi_Mirrored[7]。");
        EmitTrie("Flags", flags, 1, "二元属性打包：Emoji[0] Emoji_Presentation[1] Emoji_Modifier[2] Emoji_Modifier_Base[3] Emoji_Component[4] Default_Ignorable_Code_Point[5] White_Space[6]。");
        EmitTrie("Shaping", shaping, 2, "整形属性打包：Joining_Type[0..2] InSC[3..8] InPC[9..12] Vertical_Orientation[13..14]。");
        EmitTrie("JoiningGroup", jg, 1, "Joining_Group。");
        EmitTrie("Case", caseTrie, caseRecords.Count <= 256 ? 1 : 2, "简单大小写映射记录编号（0 表示无映射）。");
        EmitTrie("CombiningClass", ccc, 1, "Canonical_Combining_Class（0..254）。");

        // 小表
        var misc = new StringBuilder();
        misc.Append(Header()).Append("\nusing System;\n\nnamespace AwAUI.Unicode;\n\n");
        misc.Append("internal static partial class UnicodeTables\n{\n");
        misc.Append("    /// <summary>生成数据所用的 Unicode 版本。</summary>\n");
        misc.Append("    internal const string Version = \"").Append(_version).Append("\";\n\n");

        var scxOffsets = new List<byte>();
        var scxData = new List<byte>();
        foreach (var set in scxSets)
        {
            scxOffsets.Add((byte)scxData.Count);
            scxOffsets.Add((byte)(scxData.Count >> 8));
            scxData.AddRange(set);
        }
        scxOffsets.Add((byte)scxData.Count);
        scxOffsets.Add((byte)(scxData.Count >> 8));
        misc.Append("    /// <summary>Script_Extensions 集合：第 i 个集合是 ScriptExtensionData[off(i)..off(i+1))，off 为小端 16 位。</summary>\n");
        TrieBuilder.EmitBytes(misc, "ScriptExtensionOffsets", scxOffsets.ToArray());
        TrieBuilder.EmitBytes(misc, "ScriptExtensionData", scxData.ToArray());

        misc.Append("    /// <summary>大小写映射记录：每条 12 字节，依次为 lower/upper/title 相对码位的差值（小端 32 位有符号）。</summary>\n");
        var caseBytes = new List<byte>();
        foreach (var (l, u, t) in caseRecords) { Int32(caseBytes, l); Int32(caseBytes, u); Int32(caseBytes, t); }
        TrieBuilder.EmitBytes(misc, "CaseRecords", caseBytes.ToArray());

        misc.Append("    /// <summary>Bidi_Mirroring_Glyph：按码位升序的 (码位, 镜像码位) 对，各 3 字节小端。</summary>\n");
        TrieBuilder.EmitBytes(misc, "MirrorPairs", Pairs(mirrors));
        misc.Append("    /// <summary>Bidi_Paired_Bracket：按码位升序的 (码位, 配对括号) 对，各 3 字节小端。</summary>\n");
        TrieBuilder.EmitBytes(misc, "BracketPairs", Pairs(brackets));
        misc.Append("    internal const int MirrorPairCount = ").Append(mirrors.Count).Append(";\n");
        misc.Append("    internal const int BracketPairCount = ").Append(brackets.Count).Append(";\n\n");

        misc.Append("    /// <summary>各 Script 的 ISO 15924 四字母代码，按枚举值排列。</summary>\n");
        var codes = new StringBuilder();
        foreach (var m in scSpec.Members) codes.Append(m.Short);
        misc.Append("    internal const string ScriptCodes = \"").Append(codes).Append("\";\n");
        misc.Append("}\n");
        _files.Add(("UnicodeTables.Misc.g.cs", misc.ToString()));
        _sizes.Add(("ScriptExtension sets", scxOffsets.Count + scxData.Count));
        _sizes.Add(("Case records", caseBytes.Count));
        _sizes.Add(("Mirror/Bracket pairs", (mirrors.Count + brackets.Count) * 6));
        foreach (var m in scSpec.Members)
            if (m.Short.Length != 4) throw new InvalidDataException("Script code is not 4 letters: " + m.Short);

        // ---------- 写出 ----------
        Directory.CreateDirectory(outDir);
        foreach (var old in Directory.GetFiles(outDir, "*.g.cs")) File.Delete(old);
        foreach (var (name, content) in _files)
            File.WriteAllText(Path.Combine(outDir, name), content.Replace("\r\n", "\n"), new UTF8Encoding(false));
        File.Copy(_ucd.GetPathOfLicense(), Path.Combine(outDir, "UNICODE-LICENSE.txt"), overwrite: true);

        int total = 0;
        foreach (var (name, bytes) in _sizes)
        {
            Console.WriteLine($"{name,-24} {bytes,8:N0} bytes");
            total += bytes;
        }
        Console.WriteLine($"{"total",-24} {total,8:N0} bytes");
        Console.WriteLine($"wrote {_files.Count} files to {outDir}");
    }

    void EmitTrie(string name, int[] values, int width, string summary)
    {
        var trie = TrieBuilder.Build(name, values, width);
        for (int cp = 0; cp < N; cp++)
            if (trie.Lookup(cp) != values[cp]) throw new InvalidOperationException($"{name}: self-check failed at U+{cp:X4}");
        var sb = new StringBuilder();
        sb.Append(Header()).Append("\nusing System;\nusing System.Runtime.CompilerServices;\n\nnamespace AwAUI.Unicode;\n\n");
        sb.Append("internal static partial class UnicodeTables\n{\n");
        trie.Emit(sb, summary);
        var text = sb.ToString().TrimEnd('\n') + "\n}\n";
        _files.Add(($"UnicodeTables.{name}.g.cs", text));
        _sizes.Add((name + " trie", trie.TotalBytes));
    }

    static int[] Fill(int value)
    {
        var a = new int[N];
        if (value != 0) Array.Fill(a, value);
        return a;
    }

    static int B(bool b) => b ? 1 : 0;

    static void Int32(List<byte> list, int v)
    {
        list.Add((byte)v);
        list.Add((byte)(v >> 8));
        list.Add((byte)(v >> 16));
        list.Add((byte)(v >> 24));
    }

    static byte[] Pairs(SortedDictionary<int, int> map)
    {
        var bytes = new List<byte>();
        foreach (var (k, v) in map)
        {
            bytes.Add((byte)k); bytes.Add((byte)(k >> 8)); bytes.Add((byte)(k >> 16));
            bytes.Add((byte)v); bytes.Add((byte)(v >> 8)); bytes.Add((byte)(v >> 16));
        }
        return bytes.ToArray();
    }
}
