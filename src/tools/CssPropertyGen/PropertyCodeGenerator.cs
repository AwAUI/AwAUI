/// <summary>
/// 从 Properties.json 生成 AwAUI.Css 的属性代码（design/16「属性清单即代码」）。纯函数：相同输入得到逐字节相同的输出，
/// 不依赖运行时版本，测试据此在内存中重新生成并与签入的文件比对。
/// </summary>
internal static class PropertyCodeGenerator
{
    const string Header = "// <auto-generated/>\n// 由 src/tools/CssPropertyGen 从 src/AwAUI.Css/Properties.json 生成，请勿手工修改。\n#nullable enable\n";

    sealed class Group
    {
        public string Name = "";
        public bool Inherited;
        public string Doc = "";
        public readonly List<Longhand> Members = new();
        public string Type => Name + "StyleGroup";
        public string Prop => Name + "Group";
        public string Field => "_" + char.ToLowerInvariant(Name[0]) + Name.Substring(1);
    }

    sealed class EnumDef
    {
        public string Name = "";
        public List<string> Values = new();
        /// <summary>旧别名（ASCII 小写）→ 目标关键字，按别名排序。</summary>
        public SortedDictionary<string, string> Aliases = new(StringComparer.Ordinal);
    }

    sealed class Longhand
    {
        public string Name = "";
        public string Pascal = "";
        public string Type = "";
        public string? Enum;
        public List<string> Flags = new();
        public string Initial = "";
        public bool Inherited;
        public string Animatable = "";
        public string Affects = "";
        public Group Group = null!;
        public int Phase;
    }

    sealed class Shorthand
    {
        public string Name = "";
        public string Pascal = "";
        public string Parser = "";
        public List<string> Longhands = new();
        public int Phase;
    }

    /// <summary>值类型表：计算值的 C# 类型、解析/计算/序列化表达式。{0} = 枚举名，{1} = 标志表达式，{2} = 是否非负（计算表达式用），x = 字段值。</summary>
    sealed class TypeInfo
    {
        public TypeInfo(string cs, string parse, string compute, string serialize, bool op)
        {
            CsType = cs;
            Parse = parse;
            Compute = compute;
            Serialize = serialize;
            UseOperator = op;
        }

        public string CsType;
        public string Parse;
        public string Compute;
        public string Serialize;
        public bool UseOperator;
    }

