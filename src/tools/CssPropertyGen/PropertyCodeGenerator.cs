    static string GenIds(List<Longhand> longhands, List<Shorthand> shorthands, List<Group> groups)
    {
        var w = new Writer();
        w.Raw(Header);
        w.Line("namespace AwAUI.Css.Values;");
        w.Line();
        w.Line("/// <summary>属性 ID：先是全部长属性（可作为数组下标），然后是简写属性。</summary>");
        w.Line("public enum CssPropertyId : ushort");
        w.Open();
        foreach (var l in longhands) w.Line($"/// <summary><c>{l.Name}</c></summary>").Line($"{l.Pascal},");
        foreach (var s in shorthands) w.Line($"/// <summary><c>{s.Name}</c>（简写）</summary>").Line($"{s.Pascal},");
        w.Close();
        w.Line();
        w.Line("/// <summary>属性所属的 <see cref=\"ComputedStyle\"/> 分组（design/16「ComputedStyle 的存储」）。</summary>");
        w.Line("public enum CssPropertyGroup : byte");
        w.Open();
        foreach (var g in groups) w.Line($"/// <summary>{g.Doc}</summary>").Line($"{g.Name},");
        w.Close();
        w.Line();
        w.Line("public static partial class CssProperties");
        w.Open();
        w.Line("/// <summary>长属性个数（ID 0 .. LonghandCount-1）。</summary>");
        w.Line($"public const int LonghandCount = {longhands.Count};");
        w.Line();
        w.Line("/// <summary>属性总数（含简写）。</summary>");
        w.Line($"public const int Count = {longhands.Count + shorthands.Count};");
        w.Close();
        return w.ToString();
    }

    static string GenKeywords(List<EnumDef> enums)
    {
        var w = new Writer();
        w.Raw(Header);
        w.Line("namespace AwAUI.Css.Values;");
        foreach (var e in enums)
        {
            w.Line();
            w.Line($"/// <summary>关键字枚举（声明顺序即 CSS 关键字顺序）。</summary>");
            w.Line($"public enum {e.Name} : byte");
            w.Open();
            foreach (var v in e.Values) w.Line($"/// <summary><c>{v}</c></summary>").Line($"{Pascal(v)},");
            w.Close();
        }
        w.Line();
        w.Line("/// <summary>各关键字枚举的名称表（ASCII 小写），下标即枚举值。</summary>");
        w.Line("internal static class KeywordTables");
        w.Open();
        foreach (var e in enums)
        {
            var list = new StringBuilder();
            for (int i = 0; i < e.Values.Count; i++)
            {
                if (i > 0) list.Append(", ");
                list.Append('"').Append(e.Values[i]).Append('"');
            }
            if (e.Aliases.Count == 0)
            {
                w.Line($"public static readonly KeywordTable {e.Name} = new(new[] {{ {list} }});");
                continue;
            }
            var aliases = new StringBuilder();
            foreach (var kv in e.Aliases)
            {
                if (aliases.Length > 0) aliases.Append(", ");
                aliases.Append("(\"").Append(kv.Key).Append("\", ").Append(e.Values.IndexOf(kv.Value)).Append(')');
            }
            w.Line($"public static readonly KeywordTable {e.Name} = new(new[] {{ {list} }}, new[] {{ {aliases} }});");
        }
        w.Close();
        return w.ToString();
    }

    static string GenTable(List<Longhand> longhands, List<Shorthand> shorthands, List<(string Name, int Phase)> planned,
        List<(string Name, string Hint)> unsupported)
    {
        var w = new Writer();
        w.Raw(Header);
        w.Line("namespace AwAUI.Css.Values;");
        w.Line();
        w.Line("public static partial class CssProperties");
        w.Open();
        // 静态字段按文本顺序初始化：长属性数组必须写在 s_all 之前
        foreach (var s in shorthands)
        {
            w.Line($"static readonly CssPropertyId[] {LonghandsName(s)} =");
            w.Line("{");
            w.Indent++;
            foreach (var n in s.Longhands) w.Line($"CssPropertyId.{Pascal(n)},");
            w.Indent--;
            w.Line("};");
            w.Line();
        }
        w.Line("static readonly CssProperty[] s_all =");
        w.Line("{");
        w.Indent++;
        foreach (var l in longhands)
        {
            w.Line($"new(CssPropertyId.{l.Pascal}, \"{l.Name}\", inherited: {B(l.Inherited)}, CssAnimatable.{Pascal(l.Animatable)}, " +
                   $"{Affects(l.Affects)}, CssPropertyGroup.{l.Group.Name}, phase: {l.Phase}, initial: \"{Escape(l.Initial)}\", System.Array.Empty<CssPropertyId>()),");
        }
        foreach (var s in shorthands)
        {
            w.Line($"new(CssPropertyId.{s.Pascal}, \"{s.Name}\", inherited: false, CssAnimatable.No, StyleDifference.None, null, " +
                   $"phase: {s.Phase}, initial: null, {LonghandsName(s)}),");
        }
        w.Indent--;
        w.Line("};");
        w.Line();
        w.Line("/// <summary>清单中计划在后续阶段支持的属性：名称 → 期。</summary>");
        w.Line("static readonly (string Name, int Phase)[] s_planned =");
        w.Line("{");
        w.Indent++;
        foreach (var (n, p) in planned) w.Line($"(\"{n}\", {p}),");
        w.Indent--;
        w.Line("};");
        w.Line();
        w.Line("/// <summary>明确不支持的属性：名称 → 替代写法。</summary>");
        w.Line("static readonly (string Name, string Hint)[] s_unsupported =");
        w.Line("{");
        w.Indent++;
        foreach (var (n, h) in unsupported) w.Line($"(\"{n}\", \"{Escape(h)}\"),");
        w.Indent--;
        w.Line("};");
        w.Close();
        return w.ToString();
    }

    static string GenParsers(List<Longhand> longhands, List<Shorthand> shorthands)
    {
        var w = new Writer();
        w.Raw(Header);
        w.Line("using System.Collections.Generic;");
        w.Line("using AwAUI.Css.Syntax;");
        w.Line();
        w.Line("namespace AwAUI.Css.Values;");
        w.Line();
        w.Line("internal static partial class PropertyParsers");
        w.Open();
        w.Line("/// <summary>按属性语法解析长属性的值（不含 CSS 全局关键字与 var()）；无效返回 null。</summary>");
        w.Line("public static CssValue? ParseLonghand(CssPropertyId id, IReadOnlyList<CssComponentValue> value)");
        w.Open();
        w.Line("var r = new ValueReader(value);");
        w.Line("CssValue? v;");
        w.Line("switch (id)");
        w.Open();
        foreach (var l in longhands)
        {
            var t = Types[l.Type];
            w.Line($"case CssPropertyId.{l.Pascal}: v = {string.Format(CultureInfo.InvariantCulture, t.Parse, l.Enum, FlagsExpr(l.Flags))}; break;");
        }
        w.Line("default: return null;");
        w.Close();
        w.Line("return v is not null && r.AtEnd ? v : null;");
        w.Close();
        w.Line();
        w.Line("/// <summary>按简写语法展开为长属性的值，追加到 <paramref name=\"output\"/>；无效返回 false。</summary>");
        w.Line("public static bool ParseShorthand(CssPropertyId id, IReadOnlyList<CssComponentValue> value, List<PropertyValue> output)");
        w.Open();
        w.Line("switch (id)");
        w.Open();
        foreach (var s in shorthands)
            w.Line($"case CssPropertyId.{s.Pascal}: return Shorthands.{s.Parser}(value, output, CssProperties.Get(id).LonghandIds);");
        w.Line("default: return false;");
        w.Close();
        w.Close();
        w.Close();
        return w.ToString();
    }

    static string GenComputedStyle(List<Group> groups, List<Longhand> longhands)
    {
        var w = new Writer();
        w.Raw(Header);
        w.Line("using System;");
        w.Line("using AwAUI.Css.Cascade;");
        w.Line("using AwAUI.Css.Values;");
        w.Line();
        w.Line("namespace AwAUI.Css;");

        // 分组类
        foreach (var g in groups)
        {
            w.Line();
            w.Line($"/// <summary>{g.Doc}。不可变（对外），在多个 <see cref=\"ComputedStyle\"/> 之间按引用共享{(g.Inherited ? "；子元素未覆盖时与父元素共享同一实例" : "")}。</summary>");
            w.Line($"public sealed partial class {g.Type} : IEquatable<{g.Type}>");
            w.Open();
            foreach (var l in g.Members)
                w.Line($"/// <summary><c>{l.Name}</c></summary>").Line($"public {Cs(l)} {l.Pascal} {{ get; internal set; }}{(IsClass(l) ? " = null!;" : "")}").Line();
            w.Line($"internal {g.Type} Clone() => ({g.Type})MemberwiseClone();");
            w.Line();
            w.Line($"public bool Equals({g.Type}? other)");
            w.Open();
            w.Line("if (ReferenceEquals(this, other)) return true;");
            w.Line("if (other is null) return false;");
            foreach (var l in g.Members) w.Line($"if ({NotEqual(l, l.Pascal, "other." + l.Pascal)}) return false;");
            w.Line("return true;");
            w.Close();
            w.Line();
            w.Line($"public override bool Equals(object? obj) => obj is {g.Type} o && Equals(o);");
            w.Line();
            w.Line("public override int GetHashCode()");
            w.Open();
            w.Line("int h = 0;");
            foreach (var l in g.Members) w.Line($"h = HashCodeCompat.Combine(h, {Hash(l, l.Pascal)});");
            w.Line("return h;");
            w.Close();
            w.Close();
        }

        // ComputedStyle
        w.Line();
        w.Line("public sealed partial class ComputedStyle");
        w.Open();
        w.Line("internal ComputedStyle(StyleBuilder b)");
        w.Open();
        foreach (var g in groups) w.Line($"{g.Prop} = b.{g.Name};");
        w.Line("CustomProperties = b.CustomProperties;");
        w.Line("RootFontSize = b.RootFontSize;");
        w.Line("Flags = b.Flags;");
        w.Close();
        foreach (var g in groups)
        {
            w.Line();
            w.Line($"/// <summary>{g.Doc}分组。</summary>");
            w.Line($"public {g.Type} {g.Prop} {{ get; }}");
        }
        foreach (var l in longhands)
        {
            w.Line();
            w.Line($"/// <summary><c>{l.Name}</c></summary>");
            w.Line($"public {Cs(l)} {l.Pascal} => {l.Group.Prop}.{l.Pascal};");
        }
        w.Line();
        w.Line("/// <summary>逐分组比较：引用相同的分组直接跳过。</summary>");
        w.Line("static StyleDifference DiffGroups(ComputedStyle a, ComputedStyle b)");
        w.Open();
        w.Line("var d = StyleDifference.None;");
        foreach (var g in groups)
        {
            w.Line($"if (!ReferenceEquals(a.{g.Prop}, b.{g.Prop}))");
            w.Open();
            w.Line($"var x = a.{g.Prop};");
            w.Line($"var y = b.{g.Prop};");
            foreach (var l in g.Members) w.Line($"if ({NotEqual(l, "x." + l.Pascal, "y." + l.Pascal)}) d |= {Affects(l.Affects)};");
            w.Close();
        }
        w.Line("return d;");
        w.Close();
        w.Line();
        w.Line("/// <summary>长属性计算值的 CSS 文本（DevTools 的 getComputedStyle）；简写返回空串。</summary>");
        w.Line("public string GetPropertyValueText(CssPropertyId id)");
        w.Open();
        w.Line("switch (id)");
        w.Open();
        foreach (var l in longhands)
        {
            var t = Types[l.Type];
            w.Line($"case CssPropertyId.{l.Pascal}: {{ var x = {l.Group.Prop}.{l.Pascal}; return {string.Format(CultureInfo.InvariantCulture, t.Serialize, l.Enum)}; }}");
        }
        w.Line("default: return string.Empty;");
        w.Close();
        w.Close();
        w.Close();

        // StyleBuilder
        w.Line();
        w.Line("internal sealed partial class StyleBuilder");
        w.Open();
        foreach (var g in groups)
        {
            w.Line($"public {g.Type} {g.Name} = null!;");
            w.Line($"bool {g.Field}Owned;");
            w.Line();
            w.Line($"public {g.Type} Mutable{g.Name}()");
            w.Open();
            w.Line($"if (!{g.Field}Owned) {{ {g.Name} = {g.Name}.Clone(); {g.Field}Owned = true; }}");
            w.Line($"return {g.Name};");
            w.Close();
            w.Line();
        }
        w.Line("/// <summary>继承类分组取父样式的实例，非继承类分组取初始样式的实例（均未拥有，写时复制）。</summary>");
        w.Line("public void ResetGroups(ComputedStyle parent, ComputedStyle initial)");
        w.Open();
        foreach (var g in groups)
        {
            w.Line($"{g.Name} = {(g.Inherited ? "parent" : "initial")}.{g.Prop};");
            w.Line($"{g.Field}Owned = false;");
        }
        w.Close();
        w.Line();
        w.Line("/// <summary>创建全部分组的空白实例（只用于构造初始样式）。</summary>");
        w.Line("public void CreateEmptyGroups()");
        w.Open();
        foreach (var g in groups)
        {
            w.Line($"{g.Name} = new {g.Type}();");
            w.Line($"{g.Field}Owned = true;");
        }
        w.Close();
        w.Line();
        w.Line("/// <summary>从另一个样式复制一个长属性的计算值（inherit / initial / unset）。</summary>");
        w.Line("public void CopyFrom(CssPropertyId id, ComputedStyle source)");
        w.Open();
        w.Line("switch (id)");
        w.Open();
        foreach (var l in longhands)
            w.Line($"case CssPropertyId.{l.Pascal}: {{ var x = source.{l.Group.Prop}.{l.Pascal}; if ({NotEqual(l, $"{l.Group.Name}.{l.Pascal}", "x")}) Mutable{l.Group.Name}().{l.Pascal} = x; return; }}");
        w.Close();
        w.Close();
        w.Line();
        w.Line("/// <summary>把指定值计算后写入（值相同则不复制分组）。</summary>");
        w.Line("public void Apply(CssPropertyId id, CssValue value, StyleComputer c)");
        w.Open();
        w.Line("switch (id)");
        w.Open();
        foreach (var l in longhands)
        {
            var t = Types[l.Type];
            var compute = string.Format(CultureInfo.InvariantCulture, t.Compute, l.Enum, FlagsExpr(l.Flags), B(l.Flags.Contains("NonNegative")));
            w.Line($"case CssPropertyId.{l.Pascal}: {{ var x = {compute}; if ({NotEqual(l, $"{l.Group.Name}.{l.Pascal}", "x")}) Mutable{l.Group.Name}().{l.Pascal} = x; return; }}");
        }
        w.Close();
        w.Close();
        w.Close();
        return w.ToString();
    }

    // ================= 辅助 =================

    static string Cs(Longhand l) => string.Format(CultureInfo.InvariantCulture, Types[l.Type].CsType, l.Enum);

    static string NotEqual(Longhand l, string a, string b)
        => Types[l.Type].UseOperator ? $"{a} != {b}" : IsClass(l) ? $"!object.Equals({a}, {b})" : $"!{a}.Equals({b})";

    static bool IsClass(Longhand l) => Types[l.Type].CsType is "ImageList" or "ShadowList" or "FontFamilyList" or "CssGridTrackList" or "CssGridTemplateAreas";

    static string Hash(Longhand l, string a) =>
        Types[l.Type].CsType is "{0}" or "CssGridAutoFlow" ? $"(int){a}" : IsClass(l) ? $"({a}?.GetHashCode() ?? 0)" : $"{a}.GetHashCode()";

    static string FlagsExpr(List<string> flags)
    {
        if (flags.Count == 0) return "ValueFlags.None";
        var sb = new StringBuilder();
        for (int i = 0; i < flags.Count; i++)
        {
            if (i > 0) sb.Append(" | ");
            sb.Append("ValueFlags.").Append(flags[i] == "NonNegative" ? "NonNegative" : "Allow" + flags[i]);
        }
        return sb.ToString();
    }

    static string Affects(string a) => a switch
    {
        "structure" => "StyleDifference.Structure",
        "layout" => "StyleDifference.Layout",
        "paint" => "StyleDifference.Paint",
        "composite" => "StyleDifference.Composite",
        _ => "StyleDifference.Behavior",
    };

    static string LonghandsName(Shorthand s) => "s_longhands" + s.Pascal;

    static string B(bool b) => b ? "true" : "false";

    static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary><c>border-top-width</c> → <c>BorderTopWidth</c>；前导 <c>-</c> 省略。</summary>
    internal static string Pascal(string kebab)
    {
        var sb = new StringBuilder();
        bool upper = true;
        foreach (var c in kebab)
        {
            if (c == '-') { upper = true; continue; }
            sb.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }
        return sb.ToString();
    }

    static List<object?> List(Dictionary<string, object?> d, string key)
        => d.TryGetValue(key, out var v) && v is List<object?> l ? l : new List<object?>();

    static string Str(Dictionary<string, object?> d, string key)
        => d.TryGetValue(key, out var v) && v is string s ? s : throw new FormatException($"缺少字符串字段 {key}");

    static bool Bool(Dictionary<string, object?> d, string key)
        => d.TryGetValue(key, out var v) && v is bool b ? b : throw new FormatException($"缺少布尔字段 {key}");

    /// <summary>带缩进的代码写入器，固定使用 LF 与 4 空格缩进。</summary>
    sealed class Writer
    {
        readonly StringBuilder _sb = new();
        public int Indent;

        public Writer Line(string text = "")
        {
            if (text.Length > 0) _sb.Append(' ', Indent * 4).Append(text);
            _sb.Append('\n');
            return this;
        }

        public void Raw(string text) => _sb.Append(text);

        public void Open()
        {
            Line("{");
            Indent++;
        }

        public void Close()
        {
            Indent--;
            Line("}");
        }

        public override string ToString() => _sb.ToString();
    }
