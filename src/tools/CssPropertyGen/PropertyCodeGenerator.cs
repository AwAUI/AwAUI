    static (string Interp, string? Add, bool NonNegative)? InterpFor(Longhand l)
    {
        if (l.Animatable != "by-computed-value") return null;
        if (PropertyInterps.TryGetValue(l.Name, out var p)) return p;
        return Interps.TryGetValue(l.Type, out var t) ? t : null;
    }

    /// <summary>生成全部文件：文件名 → 内容（LF 换行）。</summary>
    public static SortedDictionary<string, string> Generate(string json)
    {
        var root = (Dictionary<string, object?>)(MiniJson.Parse(json) ?? throw new FormatException("空清单"));
        var groups = new List<Group>();
        var groupByName = new Dictionary<string, Group>(StringComparer.Ordinal);
        foreach (var o in List(root, "groups"))
        {
            var d = (Dictionary<string, object?>)o!;
            var g = new Group { Name = Str(d, "name"), Inherited = Bool(d, "inherited"), Doc = Str(d, "doc") };
            groups.Add(g);
            groupByName.Add(g.Name, g);
        }

        var enums = new List<EnumDef>();
        var enumByName = new Dictionary<string, EnumDef>(StringComparer.Ordinal);
        foreach (var o in List(root, "enums"))
        {
            var d = (Dictionary<string, object?>)o!;
            var e = new EnumDef { Name = Str(d, "name") };
            foreach (var v in List(d, "values")) e.Values.Add((string)v!);
            if (d.TryGetValue("aliases", out var al) && al is Dictionary<string, object?> aliases)
            {
                foreach (var kv in aliases)
                {
                    var target = kv.Value as string ?? throw new FormatException($"{e.Name}: 别名 {kv.Key} 的目标必须是字符串");
                    if (!e.Values.Contains(target)) throw new FormatException($"{e.Name}: 别名 {kv.Key} 的目标 {target} 不是该枚举的关键字");
                    if (kv.Key != kv.Key.ToLowerInvariant() || e.Values.Contains(kv.Key)) throw new FormatException($"{e.Name}: 别名 {kv.Key} 无效");
                    e.Aliases.Add(kv.Key, target);
                }
            }
            enums.Add(e);
            enumByName.Add(e.Name, e);
        }

        var names = new HashSet<string>(StringComparer.Ordinal);
        var longhands = new List<Longhand>();
        foreach (var o in List(root, "longhands"))
        {
            var d = (Dictionary<string, object?>)o!;
            var l = new Longhand
            {
                Name = Str(d, "name"),
                Type = Str(d, "type"),
                Enum = d.TryGetValue("enum", out var en) ? (string?)en : null,
                Initial = Str(d, "initial"),
                Inherited = Bool(d, "inherited"),
                Animatable = Str(d, "animatable"),
                Affects = Str(d, "affects"),
                Phase = (int)(double)d["phase"]!,
                Computed = !d.TryGetValue("computed", out var computed) || computed is not bool b || b,
            };
            if (d.TryGetValue("logical", out var logical) && logical is Dictionary<string, object?> lm)
            {
                l.LogicalLtr = Str(lm, "ltr");
                l.LogicalRtl = Str(lm, "rtl");
            }
            l.Pascal = Pascal(l.Name);
            if (d.TryGetValue("flags", out var flags) && flags is List<object?> fl)
                foreach (var f in fl)
                {
                    if (!KnownFlags.Contains((string)f!)) throw new FormatException($"{l.Name}: 未知标志 {f}");
                    l.Flags.Add((string)f!);
                }
            if (!Types.ContainsKey(l.Type)) throw new FormatException($"{l.Name}: 未知类型 {l.Type}");
            if ((l.Type is "Keyword" or "Cursor" or "KeywordList" or "ScrollbarGutter") && (l.Enum is null || !enumByName.ContainsKey(l.Enum)))
                throw new FormatException($"{l.Name}: 缺少或未知的枚举 {l.Enum}");
            if (l.Type == "Raw" && string.IsNullOrEmpty(l.Enum))
                throw new FormatException($"{l.Name}: Raw 类型需要以 enum 字段给出解析器名");
            if (!groupByName.TryGetValue(Str(d, "group"), out var g)) throw new FormatException($"{l.Name}: 未知分组");
            if (g.Inherited != l.Inherited) throw new FormatException($"{l.Name}: 继承性与分组 {g.Name} 不一致");
            if (l.Affects is not ("structure" or "layout" or "paint" or "composite" or "none")) throw new FormatException($"{l.Name}: affects 无效");
            if (l.Animatable is not ("no" or "discrete" or "by-computed-value")) throw new FormatException($"{l.Name}: animatable 无效");
            if (!names.Add(l.Name)) throw new FormatException($"重复的属性 {l.Name}");
            l.Group = g;
            if (l.Computed) g.Members.Add(l);
            longhands.Add(l);
        }

        var shorthands = new List<Shorthand>();
        foreach (var o in List(root, "shorthands"))
        {
            var d = (Dictionary<string, object?>)o!;
            var s = new Shorthand { Name = Str(d, "name"), Parser = Str(d, "parser"), Phase = (int)(double)d["phase"]! };
            s.Pascal = Pascal(s.Name);
            foreach (var v in List(d, "longhands")) s.Longhands.Add((string)v!);
            if (s.Name == "all" && s.Longhands.Count == 0)
                foreach (var l in longhands) s.Longhands.Add(l.Name);
            foreach (var n in s.Longhands)
                if (!longhands.Exists(l => l.Name == n)) throw new FormatException($"{s.Name}: 未知长属性 {n}");
            if (!names.Add(s.Name)) throw new FormatException($"重复的属性 {s.Name}");
            shorthands.Add(s);
        }

        var planned = new List<(string Name, int Phase)>();
        foreach (var o in List(root, "planned"))
        {
            var d = (Dictionary<string, object?>)o!;
            var n = Str(d, "name");
            if (!names.Add(n)) throw new FormatException($"重复的属性 {n}");
            planned.Add((n, (int)(double)d["phase"]!));
        }
        var unsupported = new List<(string Name, string Hint)>();
        foreach (var o in List(root, "unsupported"))
        {
            var d = (Dictionary<string, object?>)o!;
            var n = Str(d, "name");
            if (!names.Add(n)) throw new FormatException($"重复的属性 {n}");
            unsupported.Add((n, Str(d, "hint")));
        }

        var files = new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            ["CssPropertyId.g.cs"] = GenIds(longhands, shorthands, groups),
            ["CssKeywords.g.cs"] = GenKeywords(enums),
            ["CssProperties.g.cs"] = GenTable(longhands, shorthands, planned, unsupported),
            ["PropertyParsers.g.cs"] = GenParsers(longhands, shorthands),
            ["ComputedStyle.g.cs"] = GenComputedStyle(groups, longhands),
            ["AnimationDispatch.g.cs"] = GenAnimationDispatch(groups, longhands),
        };
        return files;
    }

