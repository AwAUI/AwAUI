    static JpegHuffmanTable? s_dcLum, s_dcChrom, s_acLum, s_acChrom;

    /// <summary>
    /// 文件缺少某个 DHT 时使用的标准表（与 libjpeg-turbo 的 jpeg_std_huff_table 相同，只有 0、1 号）；
    /// 其他编号返回 null。表构造后不再修改，可在线程间共享（并发首次调用时多建一份也无妨）。
    /// </summary>
    public static JpegHuffmanTable? Standard(bool dc, int index) => (dc, index) switch
    {
        (true, 0) => s_dcLum ??= new JpegHuffmanTable(StdDcLumBits, StdDcValues),
        (true, 1) => s_dcChrom ??= new JpegHuffmanTable(StdDcChromBits, StdDcValues),
        (false, 0) => s_acLum ??= new JpegHuffmanTable(StdAcLumBits, StdAcLumValues),
        (false, 1) => s_acChrom ??= new JpegHuffmanTable(StdAcChromBits, StdAcChromValues),
        _ => null,
    };

    public JpegHuffmanTable(byte[] counts, byte[] values)
    {
        // counts[1..16] 为各长度码字个数
        Values = values;
        int code = 0, k = 0;
        for (int len = 1; len <= 16; len++)
        {
            int n = counts[len];
            if (n == 0)
            {
                MaxCode[len] = -1;
            }
            else
            {
                ValOffset[len] = k - code;
                code += n;
                k += n;
                // 长度为 len 的码字必须能放进 len 位
                if (code > (1 << len)) throw new InvalidDataException("Bad JPEG Huffman table.");
                MaxCode[len] = code - 1;
                if (len <= LookupBits)
                {
                    int first = code - n;
                    for (int c = first; c < code; c++)
                    {
                        int sym = values[ValOffset[len] + c];
                        int shift = LookupBits - len;
                        int start = c << shift, end = (c + 1) << shift;
                        ushort entry = (ushort)(len << 8 | sym);
                        for (int i = start; i < end; i++) Lookup[i] = entry;
                    }
                }
            }
            code <<= 1;
        }
        MaxCode[17] = int.MaxValue;

        for (int i = 0; i < FastAc.Length; i++)
        {
            int entry = Lookup[i];
            if (entry == 0) continue;
            int len = entry >> 8, rs = entry & 0xFF, run = rs >> 4, size = rs & 15;
            if (size == 0 || len + size > LookupBits) continue;
            int bits = (i >> (LookupBits - len - size)) & ((1 << size) - 1);
            int value = bits < 1 << (size - 1) ? bits - (1 << size) + 1 : bits;
            FastAc[i] = value << 8 | run << 4 | (len + size);
        }
    }
}
