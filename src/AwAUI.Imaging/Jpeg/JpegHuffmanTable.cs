/// <summary>
/// 规范 Huffman 表（DHT 段）。前 <see cref="LookupBits"/> 位查表直接得到「码长 + 符号」，
/// 更长的码字按 libjpeg 的 maxcode / valptr 方式逐长度比较。
/// </summary>
internal sealed class JpegHuffmanTable
{
    public const int LookupBits = 9;

    /// <summary>索引为接下来 9 位；值为 (码长 &lt;&lt; 8) | 符号，0 表示码长超过 9 位。</summary>
    public readonly ushort[] Lookup = new ushort[1 << LookupBits];
    /// <summary>MaxCode[l]：长度为 l 的最大码字，没有该长度时为 -1；MaxCode[17] 为哨兵。</summary>
    public readonly int[] MaxCode = new int[18];
    /// <summary>ValOffset[l]：长度为 l 的码字到 <see cref="Values"/> 下标的偏移。</summary>
    public readonly int[] ValOffset = new int[17];
    public readonly byte[] Values;
    /// <summary>
    /// AC 快速表：若「码字 + 幅值位」不超过 9 位，值为 (幅值 &lt;&lt; 8) | (游程 &lt;&lt; 4) | 总位数，否则为 0。
    /// EOB / ZRL 不进此表（幅值为 0）。
    /// </summary>
    public readonly int[] FastAc = new int[1 << LookupBits];

