using System;
using System.Collections;
using System.Globalization;
using AwAUI.UI;
using UIText = AwAUI.UI.Text;

namespace AwAUI.Controls.DataGrid;

/// <summary>
/// Describes one column of a <see cref="DataGrid"/>: its header, width, sort behavior, and cell content.
/// Derive from <see cref="DataGridTextColumn"/>, <see cref="DataGridCheckBoxColumn"/>, or
/// <see cref="DataGridTemplateColumn"/> for the built-in cell kinds.
/// </summary>
public abstract class DataGridColumn
{
    /// <summary>The header content: a <see cref="Node"/> or a value formatted as text.</summary>
    public object? Header { get; set; }

    /// <summary>
    /// Property path used to read and write the cell value (for example <c>"Name"</c> or <c>"Address.City"</c>).
    /// The path is resolved against each row object with public instance properties.
    /// </summary>
    public string? Binding { get; set; }

    /// <summary>The property path used for sorting; defaults to <see cref="Binding"/> when null.</summary>
    public string? SortMemberPath { get; set; }

    DataGridLength? _width;
    DataGridSortDirection _sortDirection;

    /// <summary>The grid that currently displays this column; used to rebuild when a column property changes.</summary>
    internal DataGrid? Owner { get; set; }

    /// <summary>This column's width; when null the grid's <see cref="DataGrid.ColumnWidth"/> applies.</summary>
    public DataGridLength? Width
    {
        get => _width;
        set
        {
            if (_width.HasValue == value.HasValue && (!value.HasValue || _width!.Value.Equals(value.Value))) return;
            _width = value;
            Owner?.OnColumnLayoutChanged();
        }
    }

    /// <summary>The smallest width this column can receive, in logical pixels.</summary>
    public double MinWidth { get; set; } = 24;

    /// <summary>The largest width this column can receive, in logical pixels.</summary>
    public double MaxWidth { get; set; } = double.PositiveInfinity;

    /// <summary>Whether clicking the header may sort by this column.</summary>
    public bool CanUserSort { get; set; } = true;

    /// <summary>The current sort direction of this column (managed by the grid when its header is clicked).</summary>
    public DataGridSortDirection SortDirection
    {
        get => _sortDirection;
        set
        {
            if (_sortDirection == value) return;
            _sortDirection = value;
            Owner?.OnColumnLayoutChanged();
        }
    }

    /// <summary>An optional comparer used for sorting; when null the values are compared through <see cref="IComparable"/>.</summary>
    public IComparer? Comparer { get; set; }

    /// <summary>Whether this column's cells are read-only even when the grid is editable.</summary>
    public bool IsReadOnly { get; set; }

    /// <summary>The width assigned by the most recent layout, in logical pixels.</summary>
    public double ActualWidth { get; internal set; }

    /// <summary>True when this column was produced by <see cref="DataGrid.AutoGenerateColumns"/>.</summary>
    internal bool IsAutoGenerated { get; set; }

    /// <summary>Whether cells in this column can enter edit mode.</summary>
    public virtual bool CanEdit => !IsReadOnly;

    /// <summary>Builds the cell content shown when the cell is not being edited.</summary>
    internal abstract Node BuildDisplay(DataGridCell cell);

    /// <summary>Builds the editor shown while the cell is being edited, or null when the column cannot be edited.</summary>
    internal virtual Node? BuildEditor(DataGridCell cell) => null;

    /// <summary>Parses editor text into the property type of <paramref name="item"/>.</summary>
    internal virtual bool TryParseDraft(object? item, string? draft, out object? value, out string? error) =>
        DataGridBinding.TryConvert(draft, DataGridBinding.GetValueType(item, Binding), out value, out error);

    /// <summary>Reads this column's value from a row.</summary>
    internal bool TryGetValue(object? item, out object? value) => DataGridBinding.TryGet(item, Binding, out value);

    /// <summary>Reads this column's value, or null when it cannot be read.</summary>
    internal object? GetValue(object? item) => DataGridBinding.Get(item, Binding);

    /// <summary>Writes this column's value back to the row through its property setter.</summary>
    internal bool TrySetValue(object? item, object? value, out string? error) =>
        DataGridBinding.TrySet(item, Binding, value, out error);

    /// <summary>The value used for sorting (the <see cref="SortMemberPath"/> when supplied).</summary>
    internal object? GetSortValue(object? item) => DataGridBinding.Get(item, SortMemberPath ?? Binding);

    /// <summary>The text used by <see cref="DataGridLengthUnitType.Auto"/> width estimation.</summary>
    internal virtual string GetCellText(object? item)
    {
        var value = GetValue(item);
        return Convert.ToString(value, CultureInfo.CurrentCulture) ?? "";
    }

    /// <summary>The header text used for auto sizing and the accessibility name.</summary>
    internal string GetHeaderText()
    {
        if (Header is Node) return "";
        return Convert.ToString(Header, CultureInfo.CurrentCulture) ?? "";
    }

    internal Node BuildHeaderContent()
    {
        if (Header is Node node) return node;
        return new UIText(GetHeaderText());
    }
}

/// <summary>A column whose cells show and edit a formatted text value.</summary>
public sealed class DataGridTextColumn : DataGridColumn
{
    /// <summary>An optional formatter; when null the value is formatted with the current culture.</summary>
    public Func<object?, string?>? Formatter { get; set; }

    /// <summary>An optional composite format string passed to <see cref="IFormattable"/>.</summary>
    public string? FormatString { get; set; }

    /// <summary>Formats a row value for display.</summary>
    internal string Format(object? item)
    {
        if (!TryGetValue(item, out var value)) return "";
        if (Formatter is not null) return Formatter(value) ?? "";
        if (value is IFormattable formattable && !string.IsNullOrEmpty(FormatString))
            return formattable.ToString(FormatString, CultureInfo.CurrentCulture);
        return Convert.ToString(value, CultureInfo.CurrentCulture) ?? "";
    }

    internal override Node BuildDisplay(DataGridCell cell) => new UIText(Format(cell.Item));

    internal override Node? BuildEditor(DataGridCell cell) => cell.Grid.BuildTextEditor();

    internal override string GetCellText(object? item) => Format(item);
}

/// <summary>A column whose cells show a check box and toggle a boolean value.</summary>
public sealed class DataGridCheckBoxColumn : DataGridColumn
{
    /// <summary>Whether the value currently shown by the row is checked.</summary>
    internal bool IsChecked(object? item)
    {
        var value = GetValue(item);
        if (value is bool flag) return flag;
        if (value is null) return false;
        try
        {
            return Convert.ToBoolean(value, CultureInfo.InvariantCulture);
        }
        catch (Exception)
        {
            return false;
        }
    }

    internal override Node BuildDisplay(DataGridCell cell) => cell.Grid.BuildCheckBox(cell, IsChecked(cell.Item), editable: false);

    internal override Node? BuildEditor(DataGridCell cell) =>
        cell.Grid.BuildCheckBox(cell, cell.Grid.EditBoolDraft, editable: true);

    internal override bool TryParseDraft(object? item, string? draft, out object? value, out string? error) =>
        DataGridBinding.TryConvert(draft, DataGridBinding.GetValueType(item, Binding) ?? typeof(bool), out value, out error);

    internal override string GetCellText(object? item) => IsChecked(item) ? "true" : "false";
}

/// <summary>A read-only column whose cells come from a template.</summary>
public sealed class DataGridTemplateColumn : DataGridColumn
{
    /// <summary>Builds the content of a cell from its row item. Null shows the item through <see cref="Node.From"/>.</summary>
    public Func<object?, Node>? CellTemplate { get; set; }

    /// <inheritdoc />
    public override bool CanEdit => false;

    internal override Node BuildDisplay(DataGridCell cell) =>
        CellTemplate?.Invoke(cell.Item) ?? Node.From(cell.Item) ?? new UIText("");
}
