    }

    [Fact]
    public void AW1001_assignment_to_own_props()
    {
        var (gen, diags, errors) = Run(Usings + """
            public partial class Bad : Component
            {
                public int Count { get; set; }
                public string Title { get; set; } = "";

                public Bad() { Count = 1; }                                // 构造函数中允许

                void Increment() { Count++; this.Title = "x"; }           // 两处 AW1001

                protected override Node Build()
                {
                    var other = new Bad { Count = 2, Title = "ok" };       // 初始化器属于另一个对象
                    Title += "!";                                          // AW1001
                    return new Div { Children = [other] };
                }

                class Nested { public int Count; void M() { Count = 3; } } // 嵌套类型的同名成员
            }
            """);
        Assert.Empty(errors);
        Assert.Single(gen);
        var aw1001 = diags.Where(d => d.Id == "AW1001").ToArray();
        Assert.Equal(3, aw1001.Length);
        Assert.All(aw1001, d => Assert.Equal(RoslynSeverity.Warning, d.Severity));
        Assert.Contains(aw1001, d => d.GetMessage().Contains("'Title'"));
        Assert.Contains(aw1001, d => d.GetMessage().Contains("'Count'"));
    }

    [Fact]
    public void File_local_component_gets_a_diagnostic_instead_of_uncompilable_glue()
    {
        // file 类型的所有 partial 声明必须位于同一文件，生成的另一份声明无法编译
        var (gen, diags, errors) = Run(Usings + """
            file partial class Local : Component
            {
                public int X { get; set; }
                protected override Node Build() => new Div();
            }
            """);
        Assert.Empty(errors);
        Assert.Empty(gen);
        var d = Assert.Single(diags);
        Assert.Equal("AW1009", d.Id);
        Assert.Equal(RoslynSeverity.Warning, d.Severity);
        Assert.Contains("Local", d.GetMessage());

        // 嵌套在 file 局部类型中的组件同理；生成器不能因此失败（失败会让整个编译的胶水全部丢失）
        var (gen2, diags2, errors2) = Run(Usings + """
            file partial class Holder
            {
                public partial class Inner : Component
                {
                    protected override Node Build() => new Div();
                }
            }

            public partial class Fine : Component
            {
                public int Y { get; set; }
                protected override Node Build() => new Div();
            }
            """);
        Assert.Empty(errors2);
        Assert.Equal(new[] { "AW1009" }, diags2.Select(x => x.Id).ToArray());
        Assert.Contains("this.Y = __o.Y;", Assert.Single(gen2));
    }

    [Fact]
    public void Hand_written_glue_is_not_regenerated()
    {
        var (gen, diags, errors) = Run(Usings + """
            public partial class Custom : Component
            {
                public int X { get; set; }
                protected override bool PropsEqual(Component other) => true;
                protected override void AdoptProps(Component other) => X = ((Custom)other).X;
                protected override Node Build() => new Div();
            }
            """);
        Assert.Empty(gen);
        Assert.Empty(diags); // 手写的 AdoptProps 中给 Props 赋值不是 AW1001
        Assert.Empty(errors);
    }

    [Fact]
    public void Partially_hand_written_glue_gets_the_missing_members_generated()
    {
        // 只手写 PropsEqual（例如忽略某个回调）：仍必须生成 AdoptProps，否则 Props 永远不会更新
        var (gen, diags, errors) = Run(Usings + """
            public partial class Custom : Component
            {
                public int X { get; set; }
                public int Mode { get; init; }
                protected override bool PropsEqual(Component other) => X == ((Custom)other).X;
                protected override Node Build() => new Div();
            }

            public class NotPartialHalf : Component
            {
                protected override bool PropsEqual(Component other) => true;
                protected override Node Build() => new Div();
            }
            """);
        Assert.Empty(errors);
        Assert.Equal(new[] { "AW1006" }, diags.Select(d => d.Id).ToArray()); // 非 partial 且胶水不完整
        var code = Assert.Single(gen);
        Assert.DoesNotContain("PropsEqual", code);
        Assert.Contains("protected override void AdoptProps", code);
        Assert.Contains("this.X = __o.X;", code);
        Assert.Contains("protected override bool CanAdoptProps", code);
    }

    [Fact]
    public void Shared_emitter_output_is_csharp_7_3_compatible()
    {
        var model = new ComponentGlueModel("A.B", new[] { new GlueContainingType("class", "Outer<T>") }, "C", "<U>",
            new[] { new GlueProp("Items", "global::System.Collections.Generic.List<U>", false), new GlueProp("Mode", "int", true) },
            baseHasGlue: false);
        string code = ComponentGlueEmitter.EmitFile(model);
        var tree = CSharpSyntaxTree.ParseText(code, new CSharpParseOptions(LanguageVersion.CSharp7_3));
        Assert.Empty(tree.GetDiagnostics());
        Assert.Contains("partial class C<U>", code);
        Assert.Contains("CanAdoptProps", code);

        // 标记编译器用的成员输出
        var sb = new StringBuilder();
        ComponentGlueEmitter.EmitMembers(model, sb, "");
        Assert.StartsWith("/// <summary>", sb.ToString());
        Assert.Equal("@class", ComponentGlueEmitter.Escape("class"));
        Assert.Equal(model, new ComponentGlueModel("A.B", new[] { new GlueContainingType("class", "Outer<T>") }, "C", "<U>",
            new[] { new GlueProp("Items", "global::System.Collections.Generic.List<U>", false), new GlueProp("Mode", "int", true) }, false));
    }

    static string Normalize(string s) => s.Replace("\r\n", "\n").TrimStart('﻿');
