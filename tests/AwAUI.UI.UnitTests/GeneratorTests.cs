    static readonly Lazy<ImmutableArray<MetadataReference>> References = new(() =>
    {
        var refs = new List<MetadataReference>();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        void Add(string path)
        {
            if (!string.IsNullOrEmpty(path) && File.Exists(path) && seen.Add(Path.GetFileName(path)))
                refs.Add(MetadataReference.CreateFromFile(path));
        }
        Add(typeof(Component).Assembly.Location);
        Add(typeof(Point).Assembly.Location);
        Add(typeof(AwAUI.Platform.PhysicalKey).Assembly.Location);
        if (AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") is string tpa)
        {
            foreach (var p in tpa.Split(Path.PathSeparator)) Add(p);
        }
        else
        {
            Add(typeof(object).Assembly.Location);
        }
        return refs.ToImmutableArray();
    });

    static (string[] generated, ImmutableArray<Diagnostic> diagnostics, ImmutableArray<Diagnostic> compileErrors) Run(string source)
    {
        var parse = new CSharpParseOptions(LanguageVersion.Latest);
        var compilation = CSharpCompilation.Create("GenTest",
            new[] { CSharpSyntaxTree.ParseText(source, parse, path: "Test.cs") },
            References.Value,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new[] { new ComponentGlueGenerator().AsSourceGenerator() }, parseOptions: parse);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var output, out var diagnostics);
        var result = driver.GetRunResult();
        var generated = result.GeneratedTrees.Select(t => t.GetText().ToString()).ToArray();
        var errors = output.GetDiagnostics().Where(d => d.Severity == RoslynSeverity.Error).ToImmutableArray();
        return (generated, diagnostics, errors);
    }

    const string Usings = "using System;\nusing AwAUI.UI;\n";

    [Fact]
    public void Awaui_code_behind_classes_are_left_to_the_markup_generator()
    {
        // .awaui 的代码后置文件（X.awaui.cs）即使重复写出 `: Component` 也不生成胶水：.awaui 生成器是唯一的胶水来源（否则 CS0111）
        var parse = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = new[]
        {
            CSharpSyntaxTree.ParseText(Usings + "namespace MyApp { public partial class Page : Component { public int Size { get; set; } protected override Node Build() => new Div(); } }", parse, path: "Pages/Page.awaui.cs"),
            CSharpSyntaxTree.ParseText(Usings + "namespace MyApp { public partial class Other : Component { public int Size { get; set; } protected override Node Build() => new Div(); } }", parse, path: "Other.cs"),
        };
        var compilation = CSharpCompilation.Create("GenTest", trees, References.Value,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new[] { new ComponentGlueGenerator().AsSourceGenerator() }, parseOptions: parse);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out _, out var diagnostics);
        var generated = driver.GetRunResult().GeneratedTrees.Select(t => t.GetText().ToString()).ToArray();
        Assert.Empty(diagnostics);
        Assert.Single(generated);
        Assert.Contains("partial class Other", generated[0]);
    }

    [Fact]
    public void Snapshot_simple_component()
    {
        var (gen, diags, errors) = Run(Usings + """
            namespace MyApp
            {
                public record Todo(Guid Id, string Title);

                public partial class TodoRow : Component
                {
                    public Todo Todo { get; set; } = null!;
                    public Action<Todo>? OnRemove { get; set; }
                    public int Count { get; private set; }          // 非公共 setter：不是 Prop
                    public static string Shared { get; set; } = ""; // 静态：不是 Prop
                    public string ReadOnly => "";                   // 只读：不是 Prop
                    protected override Node Build() => new Div();
                }
            }
            """);
        Assert.Empty(diags);
        Assert.Empty(errors);
        Assert.Equal(Normalize("""
            // <auto-generated/>
            #pragma warning disable
            namespace MyApp
            {
                partial class TodoRow
                {
                    /// <summary>Props 相等比较（组件胶水，自动生成）。</summary>
                    protected override bool PropsEqual(global::AwAUI.UI.Component other)
                    {
                        var __o = other as TodoRow;
                        if ((object)__o == null) return false;
                        return global::System.Collections.Generic.EqualityComparer<global::MyApp.Todo>.Default.Equals(this.Todo, __o.Todo)
                            && global::System.Collections.Generic.EqualityComparer<global::System.Action<global::MyApp.Todo>>.Default.Equals(this.OnRemove, __o.OnRemove);
                    }

                    /// <summary>从 Props 载体拷贝 Props（组件胶水，自动生成）。</summary>
                    protected override void AdoptProps(global::AwAUI.UI.Component other)
                    {
                        var __o = (TodoRow)other;
                        this.Todo = __o.Todo;
                        this.OnRemove = __o.OnRemove;
                    }
                }
            }

            """), Normalize(Assert.Single(gen)));
    }

    [Fact]
    public void Snapshot_generic_nested_init_and_inheritance()
    {
        var (gen, diags, errors) = Run(Usings + """
            namespace MyApp
            {
                public partial class Outer
                {
                    public abstract partial class Base<T> : Component
                    {
                        public T? Value { get; set; }
                    }

                    public partial class Derived : Base<int>
                    {
                        public int Step { get; init; } = 1;
                        public string @class { get; set; } = "";
                        protected override Node Build() => new Div();
                    }
                }

                // 非 partial 但手写了胶水的基类：派生类调用基类实现
                public class Manual : Component
                {
                    public int X { get; set; }
                    protected override bool PropsEqual(Component other) => X == ((Manual)other).X;
                    protected override void AdoptProps(Component other) => X = ((Manual)other).X;
                    protected override Node Build() => new Div();
                }

                public partial class FromManual : Manual
                {
                    public int Y { get; set; }
                }
            }
            """);
        Assert.Empty(diags);
        Assert.Empty(errors);
        Assert.Equal(3, gen.Length);
        var baseGlue = gen.Single(g => g.Contains("partial class Base<T>"));
        Assert.Contains("partial class Outer", baseGlue);
        Assert.Contains("EqualityComparer<T>.Default.Equals(this.Value, __o.Value)", baseGlue);
        Assert.Contains("var __o = other as Base<T>;", baseGlue);

        var derived = gen.Single(g => g.Contains("partial class Derived"));
        Assert.Equal(Normalize("""
            // <auto-generated/>
            #pragma warning disable
            namespace MyApp
            {
                partial class Outer
                {
                    partial class Derived
                    {
                        /// <summary>Props 相等比较（组件胶水，自动生成）。</summary>
                        protected override bool PropsEqual(global::AwAUI.UI.Component other)
                        {
                            var __o = other as Derived;
                            if ((object)__o == null) return false;
                            if (!base.PropsEqual(other)) return false;
                            return global::System.Collections.Generic.EqualityComparer<int>.Default.Equals(this.Step, __o.Step)
                                && global::System.Collections.Generic.EqualityComparer<string>.Default.Equals(this.@class, __o.@class);
                        }

                        /// <summary>从 Props 载体拷贝 Props（组件胶水，自动生成）。</summary>
                        protected override void AdoptProps(global::AwAUI.UI.Component other)
                        {
                            base.AdoptProps(other);
                            var __o = (Derived)other;
                            this.@class = __o.@class;
                        }

                        /// <summary>init Props 变化时不能沿用实例（组件胶水，自动生成）。</summary>
                        protected override bool CanAdoptProps(global::AwAUI.UI.Component other)
                        {
                            var __o = other as Derived;
                            if ((object)__o == null) return false;
                            if (!base.CanAdoptProps(other)) return false;
                            return global::System.Collections.Generic.EqualityComparer<int>.Default.Equals(this.Step, __o.Step);
                        }
                    }
                }
            }

            """), Normalize(derived));

        var fromManual = gen.Single(g => g.Contains("partial class FromManual"));
        Assert.Contains("base.AdoptProps(other);", fromManual);
        Assert.Contains("this.Y = __o.Y;", fromManual);
        Assert.DoesNotContain("this.X", fromManual);
    }

    [Fact]
    public void Props_of_non_partial_base_are_handled_by_derived()
    {
        var (gen, diags, errors) = Run(Usings + """
            public abstract class PlainBase : Component    // 抽象、未手写胶水、非 partial：AW1006
            {
                public int A { get; set; }
            }

            public partial class Leaf : PlainBase
            {
                public int B { get; set; }
                protected override Node Build() => new Div();
            }
            """);
        Assert.Empty(errors);
        Assert.Equal(new[] { "AW1006" }, diags.Select(d => d.Id).ToArray());
        var leaf = Assert.Single(gen);
        Assert.DoesNotContain("namespace", leaf);
        Assert.Contains("this.A = __o.A;", leaf);
        Assert.Contains("this.B = __o.B;", leaf);
        Assert.DoesNotContain("base.", leaf);
    }

    [Fact]
    public void Diagnostics_for_non_partial_and_nested_in_non_partial()
    {
        var (gen, diags, _) = Run(Usings + """
